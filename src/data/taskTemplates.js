export function maskValue(value, mode) {
  const text=String(value??'')
  if(mode==='全模糊') return '***'
  if(mode==='右模糊') return text.slice(0,2)+'**'
  if(mode==='中间模糊') return text.length>4?text.slice(0,2)+'**'+text.slice(-2):'**'
  if(mode==='左模糊') return '**'+text.slice(-2)
  return text
}
